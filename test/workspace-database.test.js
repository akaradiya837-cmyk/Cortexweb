const assert = require('node:assert/strict');
const test = require('node:test');
const {
  decryptCredentials,
  createManagedPool,
  encryptCredentials,
  exportSql,
  hostedMySqlConnectionOptions,
  importSql,
  parseSqlExport,
  validIdentifier,
  validateColumns,
  validateRow,
} = require('../workspace-database');

test('database identifiers reject SQL syntax and reserved internal fields', () => {
  assert.equal(validIdentifier('customer_records'), true);
  assert.equal(validIdentifier('customer-records'), false);
  assert.deepEqual(validateColumns([{ name: 'id', type: 'TEXT' }]).error, 'Each column needs a unique valid name and a supported type.');
});

test('table schemas and row values are validated and normalized', () => {
  const schema = validateColumns([
    { name: 'title', type: 'VARCHAR' },
    { name: 'price', type: 'DECIMAL' },
    { name: 'available', type: 'BOOLEAN' },
  ]);
  assert.equal(schema.error, undefined);
  assert.deepEqual(validateRow({ title: 'Desk', price: '12.50', available: 'true' }, schema.columns), {
    values: { title: 'Desk', price: 12.5, available: true },
  });
  assert.match(validateRow({ title: 'Desk', price: 'not-a-number' }, schema.columns).error, /price/);
});

test('SQL export round-trips safely through the restricted SQL importer', () => {
  const columns = [{ name: 'title', type: 'VARCHAR' }, { name: 'description', type: 'TEXT' }];
  const rows = [{ id: 8, title: 'Desk; "Oak"', description: "Customer's item" }];
  const sql = exportSql('products', columns, rows);
  assert.deepEqual(parseSqlExport(sql), { tableName: 'products', columns });
  assert.deepEqual(importSql(sql, 'products', columns), [{ id: 8, title: 'Desk; "Oak"', description: "Customer's item" }]);
  assert.throws(() => importSql(`${sql}\nDROP TABLE products;`, 'products', columns), /only table exports generated by CortexWeb/);
});

test('database credentials are authenticated-encrypted with the configured server key', () => {
  const previousKey = process.env.DATABASE_ENCRYPTION_KEY;
  process.env.DATABASE_ENCRYPTION_KEY = 'a'.repeat(64);
  try {
    const credentials = { host: 'db.example.com', username: 'cortex_user', password: 'secret' };
    assert.deepEqual(decryptCredentials(encryptCredentials(credentials)), credentials);
    delete process.env.DATABASE_ENCRYPTION_KEY;
    assert.throws(() => encryptCredentials(credentials), /64 hexadecimal characters/);
    process.env.DATABASE_ENCRYPTION_KEY = 'not-a-key';
    assert.throws(() => encryptCredentials(credentials), /64 hexadecimal characters/);
  } finally {
    if (previousKey === undefined) delete process.env.DATABASE_ENCRYPTION_KEY;
    else process.env.DATABASE_ENCRYPTION_KEY = previousKey;
  }
});

test('hosted MySQL configuration requires TLS for remote hosts and provisioning credentials', () => {
  const keys = ['HOSTED_MYSQL_HOST', 'HOSTED_MYSQL_PORT', 'HOSTED_MYSQL_SSL', 'HOSTED_MYSQL_USER', 'HOSTED_MYSQL_PASSWORD'];
  const previous = Object.fromEntries(keys.map((key) => [key, process.env[key]]));
  try {
    process.env.HOSTED_MYSQL_HOST = 'mysql.example.com';
    process.env.HOSTED_MYSQL_PORT = '3306';
    process.env.HOSTED_MYSQL_SSL = 'false';
    assert.throws(() => hostedMySqlConnectionOptions(), /Enable HOSTED_MYSQL_SSL/);
    process.env.HOSTED_MYSQL_SSL = 'true';
    assert.equal(hostedMySqlConnectionOptions().host, 'mysql.example.com');
    delete process.env.HOSTED_MYSQL_USER;
    delete process.env.HOSTED_MYSQL_PASSWORD;
    assert.throws(() => createManagedPool(), /HOSTED_MYSQL_USER and HOSTED_MYSQL_PASSWORD/);
  } finally {
    for (const key of keys) {
      if (previous[key] === undefined) delete process.env[key];
      else process.env[key] = previous[key];
    }
  }
});
